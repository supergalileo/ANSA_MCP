"""Drive a CATPart folder through ANSA batch mode with N parallel workers.

    python scripts/parallel_batch.py --src D:/proj/parts --out D:/proj/out \
        --mpar D:/proj/5MM.ansa_mpar --qual D:/proj/5MM.ansa_qual --workers 4

Runs outside the `ansa` MCP server on purpose. The server owns the ANSA child
process, so when ANSA's kernel dies on a piece of geometry the server dies with
it, and the host will not respawn a stdio server on its own - every crash then
costs a manual reconnect. This driver launches `ansa64.bat -nogui -exec`
directly, so nothing in the chain needs reconnecting and a crash costs one part.

How it works
------------
* Splits the folder by file size (largest first, dealt round-robin) so the
  workers finish together instead of one carrying all the big panels.
* Each worker gets its own slice folder of **hardlinks** and its own progress
  file, so two workers never touch the same part and resume is per worker.
* Watchdog on two signals: the worker process exiting, and - the one that
  actually matters - its progress file going stale. ANSA dying often leaves the
  cmd.exe wrapper alive indefinitely, so watching the process alone reports
  "still running" forever while nothing happens.
* A restarted worker is given only the parts it has not finished yet.

Three traps this file already pays for (see references/field-notes.md):
clearing a slice folder with `shutil.rmtree` trips the host's bulk-delete guard;
`json.dumps` emits `false` which is not Python; and the merged progress file must
be appended to, never rewritten, or the summary loses every earlier phase.

Layout it creates under `--out`:
    <out>/                 shared .ansa / .nas destination
    <out>/_driver/slices/  per-run, per-worker hardlink folders
    <out>/_driver/wN.py    generated runner for worker N
    <out>/_driver/wN.jsonl per-worker progress
    <out>/_driver/wN.out   ANSA's own stdout for that worker
    <out>/_driver/supervise.log

Finish with a normal `process_folder` call on the same `--out` (limit 0) to write
the summary: it reads `_progress.jsonl`, which this driver appends to.
"""

import argparse
import collections
import json
import os
import pprint
import re
import shutil
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))

# `ansa64.bat` moves between machines and drives, so the default is resolved at
# import time instead of hardcoded: an explicit ANSA_BAT wins, then ANSA_HOME,
# then the usual BETA install roots (v24 first - the version the skill is
# verified on), newest-to-oldest inside each root.
_ANSA_ROOTS = [
    r"F:\Program Files (x86)\BETA_CAE_Systems",
    r"F:\Program Files\BETA_CAE_Systems",
    r"F:\BETA_CAE_Systems",
    r"C:\Program Files\BETA_CAE_Systems",
    r"F:\ANSA",
    r"C:\Program Files (x86)\BETA_CAE_Systems",
    r"D:\Program Files\BETA_CAE_Systems",
    r"D:\BETA_CAE_Systems",
]


def find_ansa_bat():
    env = os.environ.get("ANSA_BAT")
    if env and os.path.isfile(env):
        return env
    home = os.environ.get("ANSA_HOME")
    if home and os.path.isfile(os.path.join(home, "ansa64.bat")):
        return os.path.join(home, "ansa64.bat")
    found = []
    for root in _ANSA_ROOTS:
        if not os.path.isdir(root):
            continue
        for d in sorted(os.listdir(root), reverse=True):
            bat = os.path.join(root, d, "ansa64.bat")
            if os.path.isfile(bat):
                found.append(bat)
    return found[0] if found else r"D:\Program Files\BETA_CAE_Systems\ansa_v24.1.2\ansa64.bat"


DEFAULT_ANSA_BAT = find_ansa_bat()

RUNNER_TEMPLATE = '''"""Generated by parallel_batch.py - do not edit."""
import json

PARAMS = %(params)s

_S = r"%(script)s"
_src = open(_S, encoding="utf-8").read()
_ns = {"PARAMS": PARAMS}
exec(compile(_src, _S, "exec"), _ns)
_r = _ns.get("RESULT") or {}
print("WORKER_RESULT " + json.dumps({"by_status": (_r.get("summary") or {}).get("by_status")},
                                    ensure_ascii=False))
print("WORKER_DONE")
'''


def log(msg, path):
    line = "%s %s" % (time.strftime("%H:%M:%S"), msg)
    print(line, flush=True)
    with open(path, "a", encoding="utf-8") as fh:
        fh.write(line + "\n")


def finished_parts(progress_files):
    """Part names that already have a status record, across any progress file."""
    seen = set()
    for p in progress_files:
        if not os.path.isfile(p):
            continue
        for line in open(p, encoding="utf-8", errors="ignore"):
            try:
                rec = json.loads(line)
            except Exception:
                continue
            if rec.get("status"):
                seen.add(rec.get("part"))
    return seen


def build_stems(files):
    """Authoritative output stem per input file, decided on the **whole** src list.

    Must run here, not inside a worker: a worker only sees its own slice, so a
    part number that appears at two assembly positions and lands in two slices
    gets the plain code twice and one file overwrites the other. On the 540-part
    BIW body 44 part numbers sit at 2-4 positions: 115 names collided and the run
    delivered 452 `.ansa` for 540 parts without reporting anything.
    """
    seen, out = {}, {}
    for path in sorted(files, key=os.path.basename):
        base = os.path.basename(path)
        stem = os.path.splitext(base)[0]
        parts = stem.split("_")
        code = parts[1] if len(parts) > 1 and parts[1] else stem
        if code not in seen:
            seen[code] = 1
            out[base] = code
        else:
            seen[code] += 1
            m = re.match(r"^([A-Za-z]\d+)_", base)
            out[base] = "%s__%s" % (code, m.group(1) if m else seen[code])
    return out


def link_slice(files, dest):
    """Hardlink `files` into `dest`. Never deletes an existing directory.

    An earlier version cleared the slice folder with shutil.rmtree before
    relinking; a restart with 57 stale links tripped the host's bulk-delete guard
    and killed the driver mid-batch. Every run and every restart gets a fresh
    directory instead, which is also easier to audit afterwards.
    """
    os.makedirs(dest, exist_ok=True)
    for f in files:
        target = os.path.join(dest, os.path.basename(f))
        if os.path.exists(target):
            continue
        try:
            os.link(f, target)
        except Exception:
            shutil.copy2(f, target)


def launch(script_path, workdir, logpath, ansa_bat):
    """Start one ANSA batch process through a generated .bat wrapper.

    `ansa64.bat` is a batch file, so anything containing spaces has to survive
    cmd.exe parsing. Writing the wrapper once and running it is far more
    reliable than quoting the arguments from Python.
    """
    bat = script_path.replace(".py", ".bat")
    with open(bat, "w", encoding="utf-8", newline="\r\n") as fh:
        fh.write("@echo off\n")
        fh.write('call "%s" -nogui -nolauncher -exec "load_script: \'%s\'"\n'
                 % (ansa_bat, script_path.replace("\\", "/")))
    out = open(logpath, "a", encoding="utf-8", errors="ignore")
    out.write("\n=== launch %s ===\n" % time.strftime("%H:%M:%S"))
    out.flush()
    return subprocess.Popen([bat], cwd=workdir, stdout=out, stderr=subprocess.STDOUT)


def write_runner(path, params, mpar, qual, engine, nas, scripts_dir):
    p = dict(params)
    p.update({"mpar": mpar, "qual": qual, "engine": engine, "nas": nas,
              "scripts_dir": scripts_dir, "order": "size", "resume": True,
              "limit": 0, "write_summary": False})
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(RUNNER_TEMPLATE % {"params": pprint.pformat(p, width=110),
                                    "script": os.path.join(scripts_dir, "process_folder.py")})


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", required=True, help="folder of CATParts to process")
    ap.add_argument("--out", required=True, help="shared output folder")
    ap.add_argument("--mpar", default="", help=".ansa_mpar mesh parameters")
    ap.add_argument("--qual", default="", help=".ansa_qual quality criteria")
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--engine", default="mesh", choices=["mesh", "batchmesh"])
    ap.add_argument("--nas", type=int, default=1, help="1 = export a .nas per part")
    # `dest` is explicit because the rest of this file reads `args.ansa_bat`;
    # argparse would otherwise derive `ana_bat` from `--ana-bat` and the whole
    # driver dies with AttributeError before launching a single worker.
    ap.add_argument("--ana-bat", "--ansa-bat", dest="ansa_bat",
                    default=DEFAULT_ANSA_BAT, help="path to ansa64.bat")
    ap.add_argument("--stall", type=int, default=240,
                    help="seconds without progress before a worker counts as dead")
    ap.add_argument("--max-restarts", type=int, default=3)
    ap.add_argument("--limit", type=int, default=0, help="cap parts per worker")
    args = ap.parse_args()

    src, out = args.src, args.out
    if not os.path.isdir(src):
        print("source folder not found: %s" % src)
        return 2
    drv = os.path.join(out, "_driver")
    slices = os.path.join(drv, "slices")
    os.makedirs(slices, exist_ok=True)
    slog = os.path.join(drv, "supervise.log")
    merged_progress = os.path.join(out, "_progress.jsonl")

    files = [os.path.join(src, f) for f in sorted(os.listdir(src))
             if f.lower().endswith(".catpart")]
    prior = finished_parts([merged_progress] +
                           [os.path.join(drv, f) for f in os.listdir(drv)
                            if f.startswith("w") and f.endswith(".jsonl")])
    todo = [f for f in files if os.path.basename(f) not in prior]
    log("source %d, already recorded %d, todo %d" % (len(files), len(files) - len(todo), len(todo)), slog)
    if not todo:
        log("nothing to do", slog)
        return 0

    todo.sort(key=lambda p: os.path.getsize(p), reverse=True)
    n = max(1, min(args.workers, len(todo)))
    buckets = [[] for _ in range(n)]
    for i, f in enumerate(todo):
        buckets[i % n].append(f)
    if args.limit:
        buckets = [b[:args.limit] for b in buckets]

    run_tag = "r" + time.strftime("%H%M%S")
    stems_path = os.path.join(drv, "stems.json")
    with open(stems_path, "w", encoding="utf-8") as fh:
        json.dump(build_stems(files), fh, ensure_ascii=False)
    procs = {}
    for i, bucket in enumerate(buckets):
        w = "w%d" % (i + 1)
        wdir = os.path.join(slices, run_tag, w)
        link_slice(bucket, wdir)
        wparam = {"folder": wdir.replace("\\", "/"),
                  "out_dir": out.replace("\\", "/"),
                  "stems_file": stems_path.replace("\\", "/"),
                  "progress": os.path.join(drv, w + ".jsonl").replace("\\", "/")}
        script_path = os.path.join(slices, w + ".py")
        write_runner(script_path, wparam, args.mpar, args.qual, args.engine,
                     bool(args.nas), HERE)
        procs[w] = {"bucket": bucket, "script": script_path, "dir": wdir,
                    "progress": wparam["progress"], "restarts": 0,
                    "last_n": 0, "last_t": time.time(),
                    "popen": launch(script_path, wdir, os.path.join(drv, w + ".out"),
                                    args.ansa_bat)}
        log("%s launched with %d parts" % (w, len(bucket)), slog)

    while procs:
        time.sleep(5)
        for w in list(procs):
            info = procs[w]
            rc = info["popen"].poll()
            prog = info["progress"]
            n_now = sum(1 for _ in open(prog, encoding="utf-8", errors="ignore")) \
                if os.path.isfile(prog) else 0
            if n_now != info["last_n"]:
                info["last_n"], info["last_t"] = n_now, time.time()
            stalled = (rc is None and args.stall > 0
                       and time.time() - info["last_t"] > args.stall)
            if rc is None and not stalled:
                continue
            done = finished_parts([prog])
            left = [f for f in info["bucket"] if os.path.basename(f) not in done]
            if not left:
                log("%s finished (rc=%s), %d parts done" % (w, rc, len(info["bucket"])), slog)
                del procs[w]
                continue
            if info["restarts"] >= args.max_restarts:
                log("%s gave up after %d restarts, %d parts left"
                    % (w, info["restarts"], len(left)), slog)
                del procs[w]
                continue
            info["restarts"] += 1
            if stalled:
                log("%s stalled %.0fs with %d parts left -> kill + restart %d"
                    % (w, time.time() - info["last_t"], len(left), info["restarts"]), slog)
                subprocess.run(["taskkill", "/F", "/T", "/PID", str(info["popen"].pid)],
                               capture_output=True)
            else:
                log("%s exited rc=%s with %d parts left -> restart %d"
                    % (w, rc, len(left), info["restarts"]), slog)
            info["dir"] = os.path.join(slices, run_tag, w + "_r%d" % info["restarts"])
            link_slice(left, info["dir"])
            info["bucket"] = left
            info["last_n"], info["last_t"] = 0, time.time()
            info["popen"] = launch(info["script"], info["dir"],
                                   os.path.join(drv, w + ".out"), args.ansa_bat)

    # Append, never rewrite: this file also holds everything an earlier
    # MCP-driven phase wrote, and a rewrite silently costs the whole summary.
    merged = []
    for f in sorted(os.listdir(drv)):
        if f.startswith("w") and f.endswith(".jsonl"):
            merged.extend(x for x in open(os.path.join(drv, f), encoding="utf-8")
                          if x.strip())
    if merged:
        with open(merged_progress, "a", encoding="utf-8") as fh:
            fh.write("".join(merged))
    counts = collections.Counter()
    for f in sorted(os.listdir(drv)):
        if f.startswith("w") and f.endswith(".jsonl"):
            for line in open(os.path.join(drv, f), encoding="utf-8", errors="ignore"):
                try:
                    rec = json.loads(line)
                except Exception:
                    continue
                if rec.get("status"):
                    counts[rec["status"]] += 1
    log("appended %d progress records; worker statuses %s"
        % (len(merged), dict(counts)), slog)
    log("now run process_folder with limit=0 on %s to write the summary" % out, slog)
    return 0


if __name__ == "__main__":
    sys.exit(main())
