"""Run the Casting second pass as **one ANSA process per part**, with a timeout.

    python scripts/casting_batch.py --src <hard_parts> --out <out_casting> \
        --mpar 5MM.ansa_mpar --qual 5MM.ansa_qual --tol 2.0 --timeout 300

`casting_midsurf.py` walks a whole folder inside a single ANSA session, which is
fine for a handful of small brackets and wrong for a rescue set. Some parts do
not fail - they **hang**, with no exception and no progress (O067/O090 泡沫塑料盖,
O139/O144/O145 NVH 贴条 on the 553-part BIW body). In one process the first hang
takes the rest of the queue with it, and the rescue set is exactly where those
parts end up.

So: one part, one `ansa64.bat -nogui -exec` process, one hard timeout. A hang
costs that part only. Sequential on purpose - `casting_midsurf` appends to a
single `_casting_progress.jsonl` and concurrent writers would interleave.

Reading the result
------------------
The per-part runner prints `CASTING_RESULT {json}`; the authoritative record is
still `<out>/_casting_progress.jsonl`, which this script only ever appends to.
Statuses come straight from `casting_midsurf` (`rescued`, `rescued_var`,
`casting_partial`, `casting_failed`, `mesh_failed`) plus the two this runner adds:

    timeout   killed after --timeout seconds, no result
    died      ANSA exited without writing a record (kernel crash)
"""

import argparse
import json
import os
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from parallel_batch import find_ansa_bat  # noqa: E402  (same resolution rules)

RUNNER = '''"""Generated by casting_batch.py - do not edit."""
import json

PARAMS = %(params)s

_S = r"%(script)s"
_src = open(_S, encoding="utf-8").read()
_ns = {"PARAMS": PARAMS}
exec(compile(_src, _S, "exec"), _ns)
_r = _ns.get("RESULT") or {}
print("CASTING_RESULT " + json.dumps({"by_status": _r.get("by_status")},
                                     ensure_ascii=False))
print("CASTING_DONE")
'''


def log(msg, path):
    line = "%s %s" % (time.strftime("%H:%M:%S"), msg)
    print(line, flush=True)
    with open(path, "a", encoding="utf-8") as fh:
        fh.write(line + "\n")


def run_one(cat, params, out, ansa_bat, timeout, tag):
    """Launch one ANSA for one part. Returns (status, note)."""
    script = os.path.join(out, "_driver", "cast_%s.py" % tag)
    with open(script, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(RUNNER % {"params": repr({"catpart": cat, **params}),
                           "script": os.path.join(HERE, "casting_midsurf.py")})
    bat = script.replace(".py", ".bat")
    with open(bat, "w", encoding="utf-8", newline="\r\n") as fh:
        fh.write("@echo off\n")
        fh.write('call "%s" -nogui -nolauncher -exec "load_script: \'%s\'"\n'
                 % (ansa_bat, script.replace("\\", "/")))
    logpath = os.path.join(out, "_driver", "cast_%s.out" % tag)
    t0 = time.time()
    with open(logpath, "a", encoding="utf-8", errors="ignore") as out_fh:
        proc = subprocess.Popen([bat], cwd=os.path.dirname(bat), stdout=out_fh,
                                stderr=subprocess.STDOUT)
        try:
            proc.wait(timeout=timeout)
            rc = proc.returncode
        except subprocess.TimeoutExpired:
            subprocess.run(["taskkill", "/F", "/T", "/PID", str(proc.pid)],
                           capture_output=True)
            return "timeout", "超过 %ds 未返回，已结束进程" % timeout, time.time() - t0
    return ("exited", "rc=%s" % rc), None, time.time() - t0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", required=True, help="folder of CATParts to rescue")
    ap.add_argument("--out", required=True, help="output folder for .ansa/.nas")
    ap.add_argument("--mpar", default="")
    ap.add_argument("--qual", default="")
    ap.add_argument("--tol", type=float, default=2.0,
                    help="thickness_tolerance; 1.0 silently drops walls")
    ap.add_argument("--min-face-rate", type=float, default=90.0)
    ap.add_argument("--max-thickness", type=float, default=6.0)
    ap.add_argument("--timeout", type=int, default=300, help="seconds per part")
    ap.add_argument("--ana-bat", "--ansa-bat", dest="ansa_bat", default=find_ansa_bat())
    ap.add_argument("--nas", type=int, default=1)
    ap.add_argument("--only", default="", help="JSON list of file names to run")
    args = ap.parse_args()

    os.makedirs(os.path.join(args.out, "_driver"), exist_ok=True)
    logpath = os.path.join(args.out, "_driver", "casting_batch.log")
    progress = os.path.join(args.out, "_casting_progress.jsonl")
    done = set()
    if os.path.isfile(progress):
        for line in open(progress, encoding="utf-8", errors="ignore"):
            try:
                done.add(json.loads(line).get("part"))
            except Exception:
                pass

    files = sorted(os.path.join(args.src, f) for f in os.listdir(args.src)
                   if f.lower().endswith(".catpart"))
    if args.only:
        keep = set(json.load(open(args.only, encoding="utf-8")))
        files = [f for f in files if os.path.basename(f) in keep]
    todo = [f for f in files if os.path.basename(f) not in done]
    log("source %d, already recorded %d, todo %d" % (len(files), len(files) - len(todo),
                                                     len(todo)), logpath)
    log("ansa: %s" % args.ansa_bat, logpath)

    base_params = {"out_dir": args.out.replace("\\", "/"),
                   "engine": "mesh", "mpar": args.mpar, "qual": args.qual,
                   "thickness_tolerance": args.tol,
                   "min_face_rate": args.min_face_rate,
                   "max_thickness": args.max_thickness,
                   "tolerance": 0.15, "change_option": "macro perimeters",
                   "nas": bool(args.nas), "resume": False}

    added = []
    for i, cat in enumerate(todo, 1):
        name = os.path.basename(cat)
        tag = os.path.splitext(name)[0]
        before = os.path.getsize(progress) if os.path.isfile(progress) else 0
        res, note, secs = run_one(cat, base_params, args.out, args.ansa_bat,
                                  args.timeout, tag)
        rec = None
        if os.path.isfile(progress) and os.path.getsize(progress) > before:
            # Slice **bytes**, not characters: the note carries Chinese, so a
            # character offset from a `getsize` byte count lands mid-record and
            # parses as garbage - which then looks exactly like a crash.
            with open(progress, "rb") as fh:
                fh.seek(before)
                tail = fh.read().decode("utf-8", "ignore").strip().split("\n")
            try:
                rec = json.loads(tail[-1])
            except Exception:
                rec = None
        if rec and rec.get("part") == name:
            log("%d/%d %6.1fs %-40s %-16s %s" % (i, len(todo), secs, name,
                                                 rec.get("status"),
                                                 rec.get("note") or ""), logpath)
        else:
            status = "timeout" if res == "timeout" else "died"
            rec = {"part": name, "code": os.path.splitext(name)[0].split("_")[-1],
                   "status": status, "seconds": round(secs, 1),
                   "note": note or "ANSA 未写出记录即退出"}
            with open(progress, "a", encoding="utf-8") as fh:
                fh.write(json.dumps(rec, ensure_ascii=False) + "\n")
            log("%d/%d %6.1fs %-40s %-16s %s" % (i, len(todo), secs, name,
                                                 status, rec["note"]), logpath)
        added.append(rec)

    counts = {}
    for r in added:
        counts[r.get("status")] = counts.get(r.get("status"), 0) + 1
    log("per-part processes: %s" % counts, logpath)
    return 0


if __name__ == "__main__":
    sys.exit(main())
